"""Интерактивное меню очистки данных Диантуса.

Позволяет очистить КАЖДУЮ часть отдельно:
  1. Заказы          (клиенты, справочник, поставки — на месте)
  2. Клиенты         (админы, справочник, поставки — на месте)
  3. Справочник      (поставки, заказы, клиенты — на месте)
  4. Поставки        (справочник, заказы, клиенты — на месте)
  5. На складе       (снять с полок; всё остальное — на месте)
  6. Всё сразу       (полная очистка — ОСТОРОЖНО!)

Запуск:  python clear_data.py
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

# Импортируем функции из отдельных скриптов
from clear_orders import clear_orders
from clear_clients import clear_clients
from clear_products import clear_products
from clear_supplies import clear_supplies
from clear_stock import clear_stock


MENU = """
╔══════════════════════════════════════════════════════════╗
║   🌸 Диантус — управление данными                        ║
╠══════════════════════════════════════════════════════════╣
║   1. 🗑  Очистить ЗАКАЗЫ                                  ║
║         (клиенты, справочник, поставки — на месте)        ║
║   2. 🗑  Очистить КЛИЕНТОВ                                ║
║         (админы, справочник, поставки — на месте)         ║
║   3. 🗑  Очистить СПРАВОЧНИК ТОВАРОВ                      ║
║         (поставки, заказы, клиенты — на месте)            ║
║   4. 🗑  Очистить ПОСТАВКИ                                ║
║         (справочник, заказы, клиенты — на месте)          ║
║   5. 🧹 Снять всё с ПОЛОК (обнулить «На складе»)          ║
║         (товары, поставки, заказы, клиенты — на месте)    ║
║   6. 💥 ОЧИСТИТЬ ВСЁ (заказы + клиенты + справочник +     ║
║         поставки + полки) — очень осторожно!              ║
║   0. Выход                                                ║
╚══════════════════════════════════════════════════════════╝
"""


def clear_all() -> None:
    print("💥 ЭТО УДАЛИТ ВСЁ: заказы, клиентов, товары, поставки.")
    print("   Админы останутся.")
    if input("Точно продолжить? Введите YES: ") != "YES":
        print("Отменено.")
        return

    clear_orders()
    clear_clients()
    clear_products()
    clear_supplies()

    print("\n✅ Полная очистка завершена.")


def main() -> None:
    actions = {
        "1": ("Заказы", clear_orders),
        "2": ("Клиенты", clear_clients),
        "3": ("Справочник", clear_products),
        "4": ("Поставки", clear_supplies),
        "5": ("Полки", clear_stock),
        "6": ("Всё сразу", clear_all),
    }
    while True:
        print(MENU)
        choice = input("Выберите пункт [0-6]: ").strip()
        if choice == "0":
            print("Выход.")
            return
        if choice not in actions:
            print("❌ Неверный выбор. Попробуйте снова.\n")
            continue
        name, func = actions[choice]
        print(f"\n▶  {name}\n" + "─" * 50)
        try:
            func()
        except Exception as e:
            print(f"❌ Ошибка при выполнении: {e}")
        input("\nНажмите Enter, чтобы вернуться в меню…")


if __name__ == "__main__":
    main()