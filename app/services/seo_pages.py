def collect(db: Session, section: Section) -> dict:
    """Позиции раздела в наличии и цифры для текста. Одна строка на товар (самая новая позиция)."""
    items = (db.query(SupplyItem)
             .options(joinedload(SupplyItem.product).joinedload(Product.kind_ref),
                      joinedload(SupplyItem.product).joinedload(Product.country_ref),
                      joinedload(SupplyItem.product).joinedload(Product.height_ref))
             .join(Product, SupplyItem.product_id == Product.id)
             .filter(SupplyItem.is_active.is_(True))
             .all())
    kinds = {k.lower() for k in section.kinds}
    best: dict[int, SupplyItem] = {}
    for it in items:
        p = it.product
        if kinds and (p.kind_name or "").lower() not in kinds:
            continue
        if section.country and (p.country_name or "").lower() != section.country.lower():
            continue
        if section.name_like and section.name_like not in (p.name or "").lower():
            continue
        if it.available_stems < 1:
            continue
        if p.id not in best or it.id > best[p.id].id:
            best[p.id] = it
    rows = sorted(best.values(), key=lambda it: ((it.product.name or "").lower(), it.id))
    countries = [name for name, _n in Counter(
        it.product.country_name for it in rows if it.product.country_name).most_common()]
    heights = sorted({it.product.height_cm for it in rows if it.product.height_cm})
    packs = sorted({max(1, it.product.package_size or 1) for it in rows})
    return {
        "rows": rows,
        "count": len(rows),
        "countries": countries,
        "height_min": heights[0] if heights else 0,
        "height_max": heights[-1] if heights else 0,
        "packs": packs,
    }


def sections_for_product(product) -> list[Section]:
    """Разделы /optom/…, к которым относится товар: сначала общий по виду («Розы оптом»), затем уточняющие
    (по стране — «Эквадорские розы», по названию — «Кустовая роза»). Нужны для ссылок с карточки товара."""
    kind = (product.kind_name or "").strip().lower()
    country = (product.country_name or "").strip().lower()
    name = (product.name or "").lower()
    found = []
    for s in SECTIONS:
        if not s.kinds or kind not in {k.lower() for k in s.kinds}:
            continue
        if s.country and s.country.lower() != country:
            continue
        if s.name_like and s.name_like not in name:
            continue
        found.append(s)
    found.sort(key=lambda s: bool(s.country or s.name_like))     # общий раздел — первым (sort устойчивый)
    return found[:3]


def join_words(words: list[str]) -> str:
    """['Эквадор', 'Кения', 'Россия'] → «Эквадор, Кения и Россия»."""
    words = [w for w in words if w]
    if len(words) <= 1:
        return "".join(words)
    return ", ".join(words[:-1]) + " и " + words[-1]


